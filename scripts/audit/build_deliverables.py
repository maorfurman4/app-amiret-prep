"""Builds docs/audit/flagged-items.md and docs/audit/dry-run-fixes.sql from the
audit outputs. Read-only: it only writes local files.

Usage: python3 scripts/audit/build_deliverables.py
"""
import json, os

ROOT = os.path.join(os.path.dirname(__file__), '..', '..', 'docs', 'audit')
items = {q['id']: q for q in json.load(open(os.path.join(ROOT, 'data', 'items.json')))}
judged = [json.loads(l) for l in open(os.path.join(ROOT, 'progress.ndjson'))]
too_easy = json.load(open(os.path.join(ROOT, 'confirmed-too-easy.json')))

# Judge slips verified by hand (stored key is right, judge mis-indexed).
JUDGE_ERRORS = {'3d427d54-f004-4b6a-b2e4-739d2a7ff4d8'}
CORRECTNESS = {'key_mismatch', 'no_correct', 'ambiguous', 'distractor_correct', 'unsupported'}

# ── flagged-items.md ────────────────────────────────────────────────────────
order = ['key_mismatch', 'no_correct', 'ambiguous', 'distractor_correct', 'unsupported',
         'wording', 'grammar', 'cross_cue', 'passage_error']
lines = ['# Flagged items — blind LLM sample (2,520 items)', '',
         'Generated by `scripts/audit/build_deliverables.py`. Reasons are the judge\'s, unverified unless',
         'listed as verified in `docs/CONTENT-AUDIT.md`. Judge slips (stored key verified correct) are omitted.', '']
for flag in order:
    rows = [r for r in judged if flag in r['flags'] and r['id'] not in JUDGE_ERRORS]
    if not rows:
        continue
    lines += [f'## {flag} ({len(rows)})', '', '| id | type | lvl | judge reason |', '|---|---|---|---|']
    for r in sorted(rows, key=lambda r: (r['type'], r['id'])):
        reason = r['reason'].replace('|', '/').replace('\n', ' ')
        lines.append(f"| `{r['id']}` | {r['type']} | {r['stored_level']} | {reason} |")
    lines.append('')
open(os.path.join(ROOT, 'flagged-items.md'), 'w').write('\n'.join(lines))

# ── dry-run-fixes.sql ───────────────────────────────────────────────────────
# Verified-by-hand text fixes: (table, id, old fragment, new fragment).
TEXT_FIXES = [
    ('passages', '8e7621cb-fb3d-4cb3-99cb-3727e606c834', 'a otherwise comparable', 'an otherwise comparable'),
    ('passages', 'f164ac0c-cd2c-4efa-bb6d-2ef56db8d6db', 'bears a instructive', 'bears an instructive'),
    ('questions', '90f9f49d', 'what does umami primarily detect', 'what do umami receptors primarily detect'),
]
OPTION_FIXES = [  # (id prefix, old option text fragment, new)
    ('08cd4551', 'more unifiedly', 'in a more unified way'),
]
# SC stems with a stray space between the blank and punctuation ("___ ,").
STRAY_SPACE = [i for i, q in items.items()
               if q['type'] == 'sentence_completion' and any(f'___ {p}' in q['text'] for p in ',;:.')]
# Verified by hand as having no single best answer -> pull from practice and exams until rewritten.
DEACTIVATE = ['30b04cf2', '5d3bf588', 'd0588594', '68e8f73b']


def full(prefix):
    m = [i for i in items if i.startswith(prefix)]
    assert len(m) == 1, (prefix, m)
    return m[0]


deactivate = [full(p) for p in DEACTIVATE]
# LLM-flagged correctness candidates (not hand-verified): out of SCORED exams only (reversible),
# still served in practice. RC excluded: one ineligible question drops its whole passage
# from exams (pick_informative_passage requires 5 eligible questions).
llm_flagged = sorted({r['id'] for r in judged
                      if set(r['flags']) & CORRECTNESS and r['id'] not in JUDGE_ERRORS
                      and r['type'] != 'reading_comprehension' and r['id'] not in deactivate})
too_easy = [i for i in too_easy if i not in deactivate and i not in llm_flagged]
touched_q = sorted(set(deactivate) | set(llm_flagged) | set(too_easy) | set(STRAY_SPACE)
                   | {full(t[1]) for t in TEXT_FIXES if t[0] == 'questions'} | {full(o[0]) for o in OPTION_FIXES})
touched_p = sorted(t[1] for t in TEXT_FIXES if t[0] == 'passages')


def ids(xs):
    return ',\n  '.join(f"'{x}'" for x in xs)


sql = f"""-- Content-audit fixes — DRY RUN. Generated by scripts/audit/build_deliverables.py.
-- Ends in ROLLBACK: nothing persists. To apply, review, then change the last line to COMMIT.
-- See docs/CONTENT-AUDIT.md for the evidence behind each group.
BEGIN;

-- 0. Backups of every row this script touches (kept after COMMIT).
CREATE TABLE IF NOT EXISTS public.audit_backup_questions_20261019 AS
  SELECT * FROM public.questions WHERE id IN (
  {ids(touched_q)});
CREATE TABLE IF NOT EXISTS public.audit_backup_passages_20261019 AS
  SELECT * FROM public.passages WHERE id IN (
  {ids(touched_p)});
-- Backup tables are not for the API: no grants beyond the owner, RLS on with no policies.
ALTER TABLE public.audit_backup_questions_20261019 ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.audit_backup_passages_20261019 ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.audit_backup_questions_20261019, public.audit_backup_passages_20261019 FROM anon, authenticated;

-- 1. Verified text fixes (each guarded on the old text, so a re-run is a no-op).
"""
for table, key, old, new in TEXT_FIXES:
    rid = key if table == 'passages' else full(key)
    sql += (f"UPDATE public.{table} SET text = replace(text, '{old}', '{new}')\n"
            f"  WHERE id = '{rid}' AND text LIKE '%{old}%';  -- expect 1 row\n")
for key, old, new in OPTION_FIXES:
    sql += (f"UPDATE public.questions SET options = (\n"
            f"    SELECT jsonb_agg(jsonb_set(o, '{{text}}', to_jsonb(replace(o->>'text', '{old}', '{new}'))) ORDER BY n)\n"
            f"    FROM jsonb_array_elements(options) WITH ORDINALITY AS t(o, n))\n"
            f"  WHERE id = '{full(key)}' AND options::text LIKE '%{old}%';  -- expect 1 row\n")
sql += f"""UPDATE public.questions SET text = regexp_replace(text, '___ ([,;:.])', '___\\1', 'g')
  WHERE type = 'sentence_completion' AND text ~ '___ [,;:.]' AND id IN (
  {ids(sorted(STRAY_SPACE))});  -- expect {len(STRAY_SPACE)} rows

-- 2. Verified no single best answer -> deactivate until rewritten ({len(deactivate)} rows).
UPDATE public.questions SET active = false WHERE active AND id IN (
  {ids(deactivate)});

-- 3. LLM-flagged correctness candidates, SC + restatement only -> out of scored exams ({len(llm_flagged)} rows max).
UPDATE public.questions SET exam_eligible = false WHERE exam_eligible AND id IN (
  {ids(llm_flagged)});

-- 4. Confirmed too-easy SC + restatement -> out of scored exams, still in practice ({len(too_easy)} rows max).
--    RC deliberately excluded (see step 3 note); RC too-easy needs distractor rewrites.
UPDATE public.questions SET exam_eligible = false WHERE exam_eligible AND id IN (
  {ids(too_easy)});

-- 5. Check: eligible exam pool per type/level after the changes (compare with before).
SELECT type, difficulty_level, count(*) FILTER (WHERE active AND exam_eligible) AS eligible_after
  FROM public.questions GROUP BY 1, 2 ORDER BY 1, 2;

ROLLBACK;
"""
open(os.path.join(ROOT, 'dry-run-fixes.sql'), 'w').write(sql)
print(f'flagged-items.md written; SQL: backup {len(touched_q)} questions + {len(touched_p)} passages, '
      f'{len(TEXT_FIXES) + len(OPTION_FIXES)} text fixes, {len(STRAY_SPACE)} stray-space stems, '
      f'{len(deactivate)} deactivations, {len(llm_flagged)} llm-flagged -> ineligible, {len(too_easy)} too-easy -> ineligible')
